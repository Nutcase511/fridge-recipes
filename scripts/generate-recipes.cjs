const fs = require('fs')
const path = require('path')

const recipes = []
let rid = 0

function r() { rid++; return `r${rid}` }

function add(name, desc, diff, time, cuisine, emoji, ings, steps, opts) {
  const { tags, mealType, method, spicy, mainIng, season, tips, videoUrl } = opts || {}
  recipes.push({
    id: r(), name, description: desc, difficulty: diff || '简单', cookingTime: time || 15,
    cuisine: cuisine || '中餐', image: emoji || '🍳',
    coverImage: `https://source.unsplash.com/featured/?${encodeURIComponent(name)}美食`,
    videoUrl,
    ingredients: ings.map(i => ({
      name: i[0], quantity: i[1], required: i[2] !== false, type: i[3] || 'ingredient'
    })),
    steps: steps.map(s => ({ text: s, image: `https://source.unsplash.com/featured/?${encodeURIComponent(name)}烹饪` })),
    tips: tips || '',
    tags: tags || ['家常菜'],
    mealType: mealType || ['午餐', '晚餐'],
    cookingMethod: method || ['炒'],
    spiciness: spicy || '不辣',
    mainIngredient: mainIng || ['蔬菜'],
    season: season || ['春', '夏', '秋', '冬']
  })
}

